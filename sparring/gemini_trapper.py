def decide(obs, memory):
    if "rng" not in memory:
        import random
        memory["rng"] = random.Random(42)
    rng = memory["rng"]

    # Short deck card evaluation: rank 0=6 to 8=Ace
    def eval_hand(hole, board):
        cards = sorted(list(hole) + list(board), key=lambda x: x >> 2)
        if len(cards) < 5:
            return 0.0 # Preflop heuristic fallback
        
        ranks = [c >> 2 for c in cards]
        suits = [c & 3 for c in cards]
        
        flush = any(suits.count(s) >= 5 for s in range(4))
        
        # Check straight (6 to Ace)
        unique_ranks = sorted(list(set(ranks)))
        straight = False
        for i in range(len(unique_ranks) - 4):
            if unique_ranks[i+4] - unique_ranks[i] == 4:
                straight = True
        # Ace-low straight (A, 6, 7, 8, 9)
        if set([8, 0, 1, 2, 3]).issubset(set(ranks)):
            straight = True

        counts = {r: ranks.count(r) for r in unique_ranks}
        freqs = sorted(counts.values(), reverse=True)
        
        # Short deck hand ranks: 1. Flush, 2. Full House, 3. Trips, 4. Straight, 5. Two Pair, 6. Pair, 7. High Card
        if flush: return 700.0 + max(ranks)
        if freqs[0] >= 3 and len(freqs) > 1 and freqs[1] >= 2: return 600.0 + freqs[0] # Full House
        if freqs[0] >= 3: return 500.0 + freqs[0] # Trips beats straight in short deck
        if straight: return 400.0 + max(ranks)
        if freqs[0] >= 2 and freqs[1] >= 2: return 300.0 + freqs[0]
        if freqs[0] >= 2: return 200.0 + freqs[0]
        return float(max(ranks))

    # Evaluate current strength
    strength = eval_hand(obs.hole_cards, obs.board)
    
    # Preflop rough strength based on high cards and pairs
    if obs.street == Street.PREFLOP:
        ranks = [c >> 2 for c in obs.hole_cards]
        strength = sum(ranks) + (50 if len(set(ranks)) < len(ranks) else 0)

    # Style: Trap with strong hands early, check-raise heavily later
    is_strong = strength > (150 if obs.street == Street.PREFLOP else 350)
    is_later = obs.street in (Street.TURN, Street.RIVER)

    # If we trapped on flop/preflop and it's later, unleash check-raise/aggression
    if is_later and is_strong and Action.RAISE_POT in obs.legal_actions:
        return Action.RAISE_POT
    if is_later and is_strong and Action.RAISE_HALF in obs.legal_actions:
        return Action.RAISE_HALF

    # Slowplay / trap early with strong hands to induce bluffs
    if obs.street in (Street.PREFLOP, Street.FLOP) and is_strong and Action.CHECK_CALL in obs.legal_actions:
        return Action.CHECK_CALL

    # Default action selection
    if obs.to_call == 0:
        if Action.CHECK_CALL in obs.legal_actions and not is_strong:
            return Action.CHECK_CALL
        if Action.RAISE_HALF in obs.legal_actions and rng.random() < 0.4:
            return Action.RAISE_HALF
        return Action.CHECK_CALL
    else:
        if is_strong and Action.RAISE_POT in obs.legal_actions:
            return Action.RAISE_POT
        if Action.CHECK_CALL in obs.legal_actions:
            return Action.CHECK_CALL
        if Action.FOLD in obs.legal_actions:
            return Action.FOLD
            
    return Action.CHECK_CALL if Action.CHECK_CALL in obs.legal_actions else obs.legal_actions[0]
